# Instale a biblioteca panda, que permite fazer a decomposição estrutural e as bibliotecas
import pandas as pd
import matplotlib.pyplot as plt

import pandas as pd

from statsmodels.tsa.seasonal import seasonal_decompose

import matplotlib.pyplot as plt

import seaborn as sns

# importar o Excel para um dataframe, carreguei na pasta arquivo ao lado
df = pd.read_excel('pim.xlsx')
# ver as 5 primeiras entradas e as informações do banco de dados
df.head()
df.info()

# plotar gráfico da Produção Industrial mensal PIM-PF    #Aqui precisei arrumar o código pois ele não estava reconhecendo os nomes
# das colunas. Também tive que fazer a conversão da planilha pois os valores estavam como objetos e não como numeros.
df['Value'] = pd.to_numeric(df['Value'], errors='coerce')
plt.plot(df.Month, df.Value)
plt.xlabel('Mês')
plt.ylabel('PIM')
plt.show()

# Para fazer a decomposição da série, transformamos a coluna de Data (Month) em índice.
df['Month'] = pd.to_datetime(df['Month'])
df.set_index('Month', inplace=True)
df.head()

# 1. Tratar o valor nulo usando interpolação linear
df['Value'] = df['Value'].interpolate(method='linear')

# 2. Executar a decomposição da série temporal (modelo aditivo, período de 12 meses para dados mensais)
decomposicao = seasonal_decompose(df['Value'], model='additive', period=12)

# 3. Plotar os resultados da decomposição
fig = decomposicao.plot()
fig.set_size_inches(10, 8)
plt.show()

# decompõe a série de acordo com o modelo multiplicativo
result = seasonal_decompose(df['Value'], model='multiplicative', period=12)

# gera e exibe o gráfico dos componentes
fig = result.plot()
fig.set_size_inches(10, 8)
plt.show()